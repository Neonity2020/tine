#!/usr/bin/env node

import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { searchSourceFingerprint, wasmSearchGuardProblems } from "./wasm-search-guard-lib.mjs";

const root = fs.mkdtempSync(path.join(os.tmpdir(), "tine-wasm-search-guard-"));
const registry = "registry+https://github.com/rust-lang/crates.io-index";
const checksum = (character) => character.repeat(64);
const write = (relative, contents) => {
  const target = path.join(root, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, contents);
};
const pkg = ({ name, version, source, sum, dependencies = [] }) =>
  [
    "[[package]]",
    `name = ${JSON.stringify(name)}`,
    `version = ${JSON.stringify(version)}`,
    source && `source = ${JSON.stringify(source)}`,
    sum && `checksum = ${JSON.stringify(sum)}`,
    dependencies.length && `dependencies = [\n${dependencies.map((dependency) => ` ${JSON.stringify(dependency)},`).join("\n")}\n]`,
    "",
  ]
    .filter(Boolean)
    .join("\n");
const lock = ({ regexVersion = "1.2.3", regexSum = checksum("b"), unrelatedVersion = "9.0.0", dev = false } = {}) =>
  [
    "# generated by Cargo",
    "version = 4",
    "",
    pkg({
      name: "tine-search",
      version: "0.6.984",
      dependencies: ["regex", "unicode-normalization", ...(dev ? ["serde_json"] : [])],
    }),
    pkg({
      name: "regex",
      version: regexVersion,
      source: registry,
      sum: regexSum,
      dependencies: ["memchr"],
    }),
    pkg({ name: "memchr", version: "2.7.0", source: registry, sum: checksum("c") }),
    pkg({
      name: "unicode-normalization",
      version: "0.1.25",
      source: registry,
      sum: checksum("d"),
    }),
    ...(dev ? [pkg({ name: "serde_json", version: "1.0.0", source: registry, sum: checksum("e") })] : []),
    pkg({ name: "unrelated", version: unrelatedVersion, source: registry, sum: checksum("f") }),
  ].join("\n");

write("crates/tine-search/Cargo.toml", "[package]\nname = \"tine-search\"\nversion = \"0.6.984\"\n");
write("crates/tine-search/src/lib.rs", "mod fold;\npub use fold::canonical_fold;\n");
write("crates/tine-search/src/fold.rs", "pub fn canonical_fold(value: &str) -> String { value.to_lowercase() }\n");
write("crates/lsdoc-wasm/Cargo.toml", "[dependencies]\ntine-search = { path = \"../tine-search\" }\n");
write("crates/lsdoc-wasm/src/lib.rs", "pub fn search_fold(value: &str) -> String { tine_search::canonical_fold(value) }\n");
write("crates/lsdoc-wasm/Cargo.lock", lock());
write("Cargo.lock", lock({ dev: true }));
write("scripts/wasm-size-ceiling.json", '{"maxDecodedRawBytes": 4}\n');

const fingerprint = searchSourceFingerprint(root);
write(
  "src/render/wasm/lsdoc_wasm_bytes.ts",
  `export const SEARCH_SOURCE_SHA256 = ${JSON.stringify(fingerprint)};\nexport const WASM_B64 = \"Zm91cg==\";\n`,
);
assert.deepEqual(wasmSearchGuardProblems(root), [], "matching source and lock closure should pass");
assert.equal(searchSourceFingerprint(root), fingerprint, "regeneration stamp should be deterministic");

write(
  "src/render/wasm/lsdoc_wasm_bytes.ts",
  `export const SEARCH_SOURCE_SHA256 = ${JSON.stringify(fingerprint)};\nexport const WASM_B64 = \"Zml2ZXM=\";\n`,
);
assert.ok(
  wasmSearchGuardProblems(root).some((problem) =>
    problem.includes("decoded raw size is 5 bytes; ceiling is 4 bytes"),
  ),
  "a decoded Wasm payload over the checked-in raw-byte ceiling should fail",
);
write(
  "src/render/wasm/lsdoc_wasm_bytes.ts",
  `export const SEARCH_SOURCE_SHA256 = ${JSON.stringify(fingerprint)};\nexport const WASM_B64 = \"Zm91cg==\";\n`,
);

const leaf = fs.readFileSync(path.join(root, "crates/tine-search/src/fold.rs"), "utf8");
write("crates/tine-search/src/fold.rs", `${leaf}// changed\n`);
assert.ok(
  wasmSearchGuardProblems(root).some((problem) => problem.includes("stamp")),
  "editing shared leaf source should stale the vendored stamp",
);
write("crates/tine-search/src/fold.rs", leaf);

const wrapper = fs.readFileSync(path.join(root, "crates/lsdoc-wasm/src/lib.rs"), "utf8");
write("crates/lsdoc-wasm/src/lib.rs", `${wrapper}// changed bridge\n`);
assert.ok(
  wasmSearchGuardProblems(root).some((problem) => problem.includes("stamp")),
  "editing the Wasm search bridge should stale the vendored stamp",
);
write("crates/lsdoc-wasm/src/lib.rs", wrapper);

write("Cargo.lock", lock({ regexVersion: "1.2.4", regexSum: checksum("a"), dev: true }));
assert.ok(
  wasmSearchGuardProblems(root).some((problem) => problem.includes("version differs: Wasm 1.2.3, native 1.2.4")),
  "different native/Wasm shared dependency versions should fail",
);
write("Cargo.lock", lock({ dev: true }));

write("Cargo.lock", lock({ dev: true, unrelatedVersion: "10.0.0" }));
assert.deepEqual(wasmSearchGuardProblems(root), [], "unrelated native lock changes should not stale shared Wasm");

const explicitRegex = (contents) => contents.replace(
  ' "regex",',
  ` "regex 1.2.3 (${registry})",`,
);
const secondRegex = pkg({ name: "regex", version: "2.0.0", source: registry, sum: checksum("1") });
write("crates/lsdoc-wasm/Cargo.lock", `${explicitRegex(lock())}\n${secondRegex}`);
write("Cargo.lock", `${explicitRegex(lock({ dev: true }))}\n${secondRegex}`);
assert.deepEqual(
  wasmSearchGuardProblems(root),
  [],
  "version-and-source-qualified Cargo references should resolve unambiguously",
);
write("crates/lsdoc-wasm/Cargo.lock", lock());
write("Cargo.lock", lock({ dev: true }));

write("src/render/wasm/lsdoc_wasm_bytes.ts", 'export const WASM_B64 = "fixture";\n');
assert.ok(
  wasmSearchGuardProblems(root).some((problem) => problem.includes("no SEARCH_SOURCE_SHA256")),
  "missing legacy stamp should fail",
);
write(
  "src/render/wasm/lsdoc_wasm_bytes.ts",
  `export const SEARCH_SOURCE_SHA256 = ${JSON.stringify(checksum("0"))};\n`,
);
assert.ok(
  wasmSearchGuardProblems(root).some((problem) => problem.includes(`expected ${fingerprint}`)),
  "old stamp should fail with the expected regeneration fingerprint",
);

const ambiguousRegex = `${lock()}\n${secondRegex}`;
write("crates/lsdoc-wasm/Cargo.lock", ambiguousRegex);
assert.ok(
  wasmSearchGuardProblems(root).some((problem) => problem.includes('dependency "regex" resolves to 2 packages')),
  "ambiguous multi-version dependency references should fail usefully",
);

fs.rmSync(root, { recursive: true, force: true });
console.log("Wasm shared-search guard scratch fixtures OK");
