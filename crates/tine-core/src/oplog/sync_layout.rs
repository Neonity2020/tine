#[cfg(test)]
mod tests {
    #[test]
    fn compatibility_surface_has_no_layout_definitions_and_reexports_every_storage_atom() {
        const SOURCE: &str = include_str!("sync_layout.rs");
        let production = SOURCE
            .split("#[cfg(test)]")
            .next()
            .expect("compatibility surface has a production region");
        assert!(
            !production.contains("pub const"),
            "Tine core must not regain a second managed-layout source of truth"
        );
        for row in tine_storage::formats::FORMAT_MANIFEST
            .iter()
            .filter(|row| row.artifact == "managed storage layout")
        {
            assert!(
                production.contains(row.name),
                "storage-owned layout atom {} is missing from the core compatibility surface",
                row.name
            );
        }
    }
}
